func TestOverride(t *testing.T) {
	routes := []app.Route{
		{Name: "api-u1", Hostname: "api-u1.example.test", Service: "web", Port: 8001, Entrypoint: "web", Project: "acme-u1", Network: "multiversenet"},
		{Name: "devapi-u1", Hostname: "devapi-u1.example.test", Aliases: []string{"app-u1.example.test", "adm-u1.example.test"}, Service: "web", Port: 8001, Entrypoint: "devapi", Project: "acme-u1", Network: "multiversenet"},
	}
	tests := []struct {
		name      string
		routes    []app.Route
		unpublish []string
		env       []app.ServiceEnv
		want      string
	}{
		{
			name:      "shared service with aliases and unpublish",
			routes:    routes,
			unpublish: []string{"web", "db"},
			want: `# generated by multiversectl, regenerated on every start
services:
  db:
    ports: !reset []
  web:
    ports: !reset []
    labels:
      traefik.enable: "true"
      traefik.docker.network: "multiversenet"
      traefik.http.services.api-u1.loadbalancer.server.port: "8001"
      traefik.http.routers.api-u1.rule: "Host(` + "`api-u1.example.test`" + `)"
      traefik.http.routers.api-u1.entrypoints: "web"
      traefik.http.routers.api-u1.service: "api-u1"
      traefik.http.services.devapi-u1.loadbalancer.server.port: "8001"
      traefik.http.routers.devapi-u1.rule: "Host(` + "`devapi-u1.example.test`) || Host(`app-u1.example.test`) || Host(`adm-u1.example.test`" + `)"
      traefik.http.routers.devapi-u1.entrypoints: "devapi"
      traefik.http.routers.devapi-u1.service: "devapi-u1"
    networks: [default, multiversenet]
networks:
  multiversenet:
    external: true
`,
		},
		{
			// The fragment is merged last, so an environment written here is
			// what the service ends up with, whatever its own files said.
			name:      "environment asked for with labels",
			unpublish: []string{"web"},
			env: []app.ServiceEnv{{Service: "web", Vars: []app.EnvVar{
				{Name: "DJANGO_ALLOWED_HOSTS", Value: "api-u1.example.test"},
				{Name: "DJANGO_CSRF_TRUSTED_ORIGINS", Value: "http://api-u1.example.test,http://devapi-u1.example.test:8001"},
			}}},
			want: `# generated by multiversectl, regenerated on every start
services:
  web:
    ports: !reset []
    # Asked for with multiverse.env.* labels. This fragment is merged last, so
    # these win over the service's own environment and any env_file.
    environment:
      DJANGO_ALLOWED_HOSTS: "api-u1.example.test"
      DJANGO_CSRF_TRUSTED_ORIGINS: "http://api-u1.example.test,http://devapi-u1.example.test:8001"
`,
		},
		{
			name:      "unpublish only",
			unpublish: []string{"db"},
			want: `# generated by multiversectl, regenerated on every start
services:
  db:
    ports: !reset []
`,
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got, err := render("routes.yml.tmpl", buildOverride(app.OverrideRequest{
				Routes: tc.routes, Unpublish: tc.unpublish, Env: tc.env,
			}))
			if err != nil {
				t.Fatal(err)
			}
			if string(got) != tc.want {
				t.Fatalf("got:\n%s\nwant:\n%s", got, tc.want)
			}
		})
	}
}

func TestProxyTemplateRoundTrip(t *testing.T) {
	for _, bind := range []string{"0.0.0.0", "127.0.0.1"} {
		data := struct {
			Network     string
			Socket      string
			Bind        string
			Entrypoints []entrypoint
		}{"multiversenet", "/var/run/docker.sock", bind,
			sortedEntrypoints(map[string]int{"web": 80, "devapi": 8001})}
		got, err := render("proxy.yml.tmpl", data)
		if err != nil {
			t.Fatal(err)
		}
		eps := parseEntrypoints(string(got))
		if eps["web"] != 80 || eps["devapi"] != 8001 || len(eps) != 2 {
			t.Fatalf("entrypoints = %v", eps)
		}
		// A universe stays off the network only if the port is published on
		// the loopback address, so the published form is the thing to assert.
		for _, port := range []string{"80", "8001"} {
			if want := `"` + bind + ":" + port + ":" + port + `"`; !strings.Contains(string(got), want) {
				t.Errorf("want %s published as %s:\n%s", port, want, got)
			}
		}
	}
}
