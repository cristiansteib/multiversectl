func TestOverride(t *testing.T) {
	routes := []app.Route{
		{Name: "api-u1", Hostname: "api-u1.example.test", Service: "web", Port: 8001, Entrypoint: "web", Project: "acme-u1", Network: "acme-u1-web_default"},
		{Name: "devapi-u1", Hostname: "devapi-u1.example.test", Aliases: []string{"app-u1.example.test", "adm-u1.example.test"}, Service: "web", Port: 8001, Entrypoint: "devapi", Project: "acme-u1", Network: "acme-u1-web_default"},
	}
	tests := []struct {
		name      string
		routes    []app.Route
		unpublish []string
		env       []app.ServiceEnv
		want      string
	}{
		{
			name:      "shared service with aliases and unpublish",
			routes:    routes,
			unpublish: []string{"web", "db"},
			want: `# generated by multiversectl, regenerated on every start
services:
  db:
    ports: !reset []
  web:
    ports: !reset []
    labels:
      traefik.enable: "true"
      io.multiversectl.served-by: "multiverse-proxy"
      traefik.docker.network: "acme-u1-web_default"
      traefik.http.services.api-u1.loadbalancer.server.port: "8001"
      traefik.http.routers.api-u1.rule: "Host(` + "`api-u1.example.test`" + `)"
      traefik.http.routers.api-u1.entrypoints: "web"
      traefik.http.routers.api-u1.service: "api-u1"
      traefik.http.services.devapi-u1.loadbalancer.server.port: "8001"
      traefik.http.routers.devapi-u1.rule: "Host(` + "`devapi-u1.example.test`) || Host(`app-u1.example.test`) || Host(`adm-u1.example.test`" + `)"
      traefik.http.routers.devapi-u1.entrypoints: "devapi"
      traefik.http.routers.devapi-u1.service: "devapi-u1"
`,
		},
		{
			// The fragment is merged last, so an environment written here is
			// what the service ends up with, whatever its own files said.
			name:      "environment asked for with labels",
			unpublish: []string{"web"},
			env: []app.ServiceEnv{{Service: "web", Vars: []app.EnvVar{
				{Name: "DJANGO_ALLOWED_HOSTS", Value: "api-u1.example.test"},
				{Name: "DJANGO_CSRF_TRUSTED_ORIGINS", Value: "http://api-u1.example.test,http://devapi-u1.example.test:8001"},
			}}},
			want: `# generated by multiversectl, regenerated on every start
services:
  web:
    ports: !reset []
    # Asked for with dev.multiversectl.env.* labels. This fragment is merged last, so
    # these win over the service's own environment and any env_file.
    environment:
      DJANGO_ALLOWED_HOSTS: "api-u1.example.test"
      DJANGO_CSRF_TRUSTED_ORIGINS: "http://api-u1.example.test,http://devapi-u1.example.test:8001"
`,
		},
		{
			name:      "unpublish only",
			unpublish: []string{"db"},
			want: `# generated by multiversectl, regenerated on every start
services:
  db:
    ports: !reset []
`,
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got, err := render("routes.yml.tmpl", buildOverride(app.OverrideRequest{
				Routes: tc.routes, Unpublish: tc.unpublish, Env: tc.env,
			}))
			if err != nil {
				t.Fatal(err)
			}
			if string(got) != tc.want {
				t.Fatalf("got:\n%s\nwant:\n%s", got, tc.want)
			}
		})
	}
}

func TestProxyTemplateRoundTrip(t *testing.T) {
	for _, bind := range []string{"0.0.0.0", "127.0.0.1"} {
		data := proxyData{Network: "multiversenet", Socket: "/var/run/docker.sock", Bind: bind,
			Entrypoints: sortedEntrypoints(map[string]int{"web": 80, "devapi": 8001})}
		got, err := render("proxy.yml.tmpl", data)
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(string(got), "--serverstransport.insecureskipverify=true") {
			t.Error("a service behind scheme: https is reached with a self-signed certificate; the proxy must not refuse it")
		}
		eps := parseEntrypoints(string(got))
		if eps["web"] != 80 || eps["devapi"] != 8001 || len(eps) != 2 {
			t.Fatalf("entrypoints = %v", eps)
		}
		// A universe stays off the network only if the port is published on
		// the loopback address, so the published form is the thing to assert.
		for _, port := range []string{"80", "8001"} {
			if want := `"` + bind + ":" + port + ":" + port + `"`; !strings.Contains(string(got), want) {
				t.Errorf("want %s published as %s:\n%s", port, want, got)
			}
		}
	}
}

// A forwarded service publishes exactly the ports it was given, which replaces
// the unpublish reset rather than adding to it.
func TestOverridePublishesForwardedPort(t *testing.T) {
	got := buildOverride(app.OverrideRequest{
		Bind:      "0.0.0.0",
		Unpublish: []string{"web"},
		Routes: []app.Route{{Name: "api-u1", Hostname: "api-u1.example.test", Service: "web", Port: 8000, Entrypoint: "web",
			Network: "multiversenet", HostPort: 50010}},
	})
	content, err := render("routes.yml.tmpl", got)
	if err != nil {
		t.Fatal(err)
	}
	out := string(content)
	if !strings.Contains(out, "ports: !override\n      - \"0.0.0.0:50010:8000\"") {
		t.Fatalf("forwarded port missing:\n%s", out)
	}
	if strings.Contains(out, "!reset") {
		t.Fatalf("the reset must not follow the override:\n%s", out)
	}
}

// A service that speaks HTTP/2 without TLS (gRPC) is told to the proxy; one that
// does not say gets nothing, so a plain service's labels do not change.
func TestOverrideSaysWhenAServiceSpeaksH2c(t *testing.T) {
	route := func(name, scheme string) app.Route {
		return app.Route{Name: name, Hostname: name + ".example.test", Service: "web", Port: 4317, Entrypoint: "web", Network: "multiversenet", Scheme: scheme}
	}
	for scheme, want := range map[string]bool{"h2c": true, "https": true, "http": false, "": false} {
		content, err := render("routes.yml.tmpl", buildOverride(app.OverrideRequest{Routes: []app.Route{route("rpc-u1", scheme)}}))
		if err != nil {
			t.Fatal(err)
		}
		label := "traefik.http.services.rpc-u1.loadbalancer.server.scheme"
		if got := strings.Contains(string(content), label); got != want {
			t.Errorf("scheme %q: label present = %v, want %v\n%s", scheme, got, want, content)
		}
		if want && !strings.Contains(string(content), scheme) {
			t.Errorf("scheme %q is not in the labels:\n%s", scheme, content)
		}
	}
}

// A TLS entrypoint serves every router on it over https, and certificates of
// one's own reach the proxy through its file provider: both are the proxy's
// static configuration, and survive a round trip through Status.
func TestProxyTemplateServesTLSWithTheGivenCertificates(t *testing.T) {
	dir := t.TempDir()
	cert, key := filepath.Join(dir, "wild.pem"), filepath.Join(dir, "wild-key.pem")
	for _, f := range []string{cert, key} {
		if err := os.WriteFile(f, []byte("pem"), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	certs, err := mountCertificates([]domain.Certificate{{CertFile: cert, KeyFile: key}})
	if err != nil {
		t.Fatal(err)
	}
	eps := []entrypoint{{Name: "web", Port: 443, TLS: true}, {Name: "devapi", Port: 8001}}
	data := proxyData{Network: "multiversenet", Socket: "/var/run/docker.sock", Bind: "0.0.0.0", Entrypoints: eps,
		Certificates: certs, TLSFile: filepath.Join(dir, "tls.yml")}
	proxy, err := render("proxy.yml.tmpl", data)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"--entrypoints.web.http.tls=true", "--providers.file.filename=/etc/multiversectl/tls.yml",
		cert + ":/certs/0/cert.pem:ro", key + ":/certs/0/key.pem:ro"} {
		if !strings.Contains(string(proxy), want) {
			t.Errorf("want %s in:\n%s", want, proxy)
		}
	}
	var parsed struct {
		Services map[string]struct{ Volumes []string } `yaml:"services"`
	}
	if err := yaml.Unmarshal(proxy, &parsed); err != nil || len(parsed.Services["traefik"].Volumes) != 4 {
		t.Errorf("not the compose file it should be (%v): %+v\n%s", err, parsed, proxy)
	}
	if tls := parseTLS(string(proxy)); !tls["web"] || tls["devapi"] {
		t.Errorf("TLS read back as %v", tls)
	}
	conf, err := render("tls.yml.tmpl", data)
	if err != nil || !strings.Contains(string(conf), "certFile: /certs/0/cert.pem") {
		t.Errorf("tls.yml = %s, %v", conf, err)
	}
	if _, err := mountCertificates([]domain.Certificate{{CertFile: filepath.Join(dir, "missing.pem"), KeyFile: key}}); err == nil {
		t.Error("a missing certificate must be refused: docker would mount an empty directory in its place")
	}
}

// A routed service stays on its app's own network: it is attached to no network
// shared with other universes, and the label names the network the proxy reaches it
// on. A host reached by IP alone gets its published port and nothing of the proxy's.
func TestARoutedServiceJoinsNoSharedNetwork(t *testing.T) {
	out := buildOverride(app.OverrideRequest{
		Bind: "0.0.0.0",
		Routes: []app.Route{
			{Name: "web-u3", Hostname: "web-u3.example.test", Service: "web", Port: 80, Entrypoint: "web", Network: "acme-u3-web_default"},
			{Name: "api-u3", Hostname: "api-u3.example.test", Service: "api", Port: 8000, Entrypoint: "web",
				HostPort: 41000, ByIP: true},
		},
	})
	byName := map[string]*service{}
	for _, s := range out.Services {
		byName[s.Name] = s
	}
	web, api := byName["web"], byName["api"]
	if web == nil || len(web.Networks) != 0 || len(out.Networks) != 0 {
		t.Fatalf("a routed service is attached to networks %+v (fragment declares %v), want none", web, out.Networks)
	}
	var named string
	for _, l := range web.Labels {
		if l.Key == "traefik.docker.network" {
			named = l.Value
		}
	}
	if named != "acme-u3-web_default" {
		t.Errorf("the label names network %q, want the app's own acme-u3-web_default", named)
	}
	if api == nil {
		t.Fatalf("the service reached by IP has no entry: its published port is lost")
	}
	if len(api.Ports) != 1 || api.Ports[0] != "0.0.0.0:41000:8000" {
		t.Errorf("api ports = %v, want 0.0.0.0:41000:8000", api.Ports)
	}
	if len(api.Networks) != 0 || len(api.Labels) != 0 {
		t.Errorf("a service reached by IP alone has networks %v and labels %v, want none", api.Networks, api.Labels)
	}
	text, err := render("routes.yml.tmpl", out)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(text), "multiversenet") || strings.Contains(string(text), "external: true") {
		t.Errorf("a shared or external network is still in the fragment:\n%s", text)
	}
}
