// Command schemagen writes the CRD-style schema for the manifest from the
// types in internal/adapters/manifest/v1alpha1 (and, with -kind Catalog,
// internal/adapters/catalog/v1alpha1): their doc comments become
// descriptions and their +markers become constraints. Run it with `make
// schema`; CI fails when the committed file no longer matches.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strconv"
	"strings"
)

const (
	group   = "multiverse"
	version = "v1alpha1"
)

// target is one schema to write: the object kind, its plural, and the text
// that follows the generated part.
type target struct {
	kind, plural, pkg, footer string
}

var targets = map[string]target{
	"Multiverse": {kind: "Multiverse", plural: "multiverses", pkg: "manifest", footer: labelsFooter},
	"Catalog":    {kind: "Catalog", plural: "catalogs", pkg: "catalog"},
}

func main() {
	args, kindName := os.Args[1:], "Multiverse"
	if len(args) >= 2 && args[0] == "-kind" {
		kindName, args = args[1], args[2:]
	}
	t, ok := targets[kindName]
	if !ok || len(args) < 1 {
		fmt.Fprintln(os.Stderr, "usage: schemagen [-kind Multiverse|Catalog] <types.go> [more.go...]")
		os.Exit(2)
	}
	structs, err := parse(args)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	out, err := render(structs, t)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	os.Stdout.Write(out)
}

// ── reading the source ───────────────────────────────────────────────────

type field struct {
	Name    string // yaml name
	GoType  string
	Inline  bool
	Doc     string
	Markers map[string]string
}

type strukt struct {
	Name   string
	Doc    string
	Fields []field
}

func parse(paths []string) (map[string]strukt, error) {
	out := map[string]strukt{}
	for _, path := range paths {
		fset := token.NewFileSet()
		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}
				doc, _ := docAndMarkers(gen.Doc)
				s := strukt{Name: ts.Name.Name, Doc: doc}
				for _, f := range st.Fields.List {
					parsed, ok := readField(f)
					if ok {
						s.Fields = append(s.Fields, parsed)
					}
				}
				out[s.Name] = s
			}
		}
	}
	return out, nil
}

func readField(f *ast.Field) (field, bool) {
	if f.Tag == nil {
		return field{}, false
	}
	tag, err := strconv.Unquote(f.Tag.Value)
	if err != nil {
		return field{}, false
	}
	yamlTag := structTag(tag, "yaml")
	name, opts, _ := strings.Cut(yamlTag, ",")
	inline := strings.Contains(opts, "inline")
	if name == "" && !inline {
		return field{}, false
	}
	doc, markers := docAndMarkers(f.Doc)
	return field{Name: name, GoType: typeName(f.Type), Inline: inline, Doc: doc, Markers: markers}, true
}

// docAndMarkers splits a comment group into prose and +markers.
func docAndMarkers(group *ast.CommentGroup) (string, map[string]string) {
	markers := map[string]string{}
	if group == nil {
		return "", markers
	}
	var prose []string
	for _, line := range group.List {
		text := strings.TrimSpace(strings.TrimPrefix(strings.TrimPrefix(line.Text, "//"), " "))
		if strings.HasPrefix(text, "+") {
			key, value, _ := strings.Cut(strings.TrimPrefix(text, "+"), "=")
			markers[key] = value
			continue
		}
		prose = append(prose, text)
	}
	return strings.Join(prose, " "), markers
}

func structTag(tag, key string) string {
	for _, part := range strings.Fields(tag) {
		if rest, ok := strings.CutPrefix(part, key+":"); ok {
			unquoted, err := strconv.Unquote(rest)
			if err != nil {
				return ""
			}
			return unquoted
		}
	}
	return ""
}

func typeName(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.ArrayType:
		return "[]" + typeName(t.Elt)
	case *ast.SelectorExpr:
		return typeName(t.X) + "." + t.Sel.Name
	case *ast.StarExpr:
		return typeName(t.X)
	case *ast.MapType:
		return "map"
	default:
		return "unknown"
	}
}

// ── writing the schema ───────────────────────────────────────────────────

type writer struct {
	buf     bytes.Buffer
	structs map[string]strukt
}

func render(structs map[string]strukt, t target) ([]byte, error) {
	w := &writer{structs: structs}
	root, ok := structs[t.kind]
	if !ok {
		return nil, fmt.Errorf("type %s not found", t.kind)
	}
	// One TypeMeta is shared by every kind a package declares, so its +enum
	// marker can only name one of them. The kind field says which object this
	// schema describes, so it is the target's kind and not the marker's;
	// otherwise the CatalogRoot schema would refuse every CatalogRoot file.
	w.setKindEnum(root, t.kind)
	w.line(0, "# Generated by `make schema` from internal/adapters/%s/%s.", t.pkg, version)
	w.line(0, "# Edit the Go types and their doc comments, not this file.")
	w.line(0, "#")
	w.line(0, "# Written as a CustomResourceDefinition because that shape is a familiar way")
	w.line(0, "# to read what the fields are and what they mean. Nothing applies it to a")
	w.line(0, "# cluster: it documents the format and can feed a validator or an editor.")
	w.line(0, "apiVersion: apiextensions.k8s.io/v1")
	w.line(0, "kind: CustomResourceDefinition")
	w.line(0, "metadata:")
	w.line(1, "name: %s.%s", t.plural, group)
	w.line(0, "spec:")
	w.line(1, "group: %s", group)
	w.line(1, "scope: Namespaced")
	w.line(1, "names:")
	w.line(2, "kind: %s", t.kind)
	w.line(2, "plural: %s", t.plural)
	w.line(2, "singular: %s", strings.ToLower(t.kind))
	w.line(1, "versions:")
	w.line(2, "- name: %s", version)
	w.line(3, "served: true")
	w.line(3, "storage: true")
	w.line(3, "schema:")
	w.line(4, "openAPIV3Schema:")
	w.object(5, root)
	w.buf.WriteString(t.footer)
	return w.buf.Bytes(), nil
}

// object writes a struct as an object schema, flattening inline fields.
// setKindEnum makes the object's own `kind` accept exactly the kind being
// written. Only the root's kind, whether declared there or in a struct it
// inlines: `kind` is a field name others use too, such as the proxy's.
func (w *writer) setKindEnum(root strukt, kind string) {
	if w.overrideKind(root.Name, kind) {
		return
	}
	for _, f := range root.Fields {
		if f.Inline && w.overrideKind(f.GoType, kind) {
			return
		}
	}
}

// overrideKind rewrites the enum of named's `kind` field, and says whether it
// had one.
func (w *writer) overrideKind(named, kind string) bool {
	s, ok := w.structs[named]
	if !ok {
		return false
	}
	for i, f := range s.Fields {
		if f.Name != "kind" {
			continue
		}
		markers := make(map[string]string, len(f.Markers)+1)
		for k, v := range f.Markers {
			markers[k] = v
		}
		markers["enum"] = kind
		s.Fields[i].Markers = markers
		w.structs[named] = s
		return true
	}
	return false
}

func (w *writer) object(indent int, s strukt) {
	w.line(indent, "type: object")
	if s.Doc != "" {
		w.describe(indent, s.Doc)
	}
	fields := w.flatten(s)
	var required []string
	for _, f := range fields {
		if _, ok := f.Markers["required"]; ok {
			required = append(required, f.Name)
		}
	}
	if len(required) > 0 {
		sort.Strings(required)
		w.line(indent, "required: [%s]", strings.Join(required, ", "))
	}
	if len(fields) == 0 {
		return
	}
	w.line(indent, "properties:")
	for _, f := range fields {
		w.line(indent+1, "%s:", f.Name)
		w.field(indent+2, f)
	}
}

// flatten returns a struct's fields with inlined embedded structs expanded.
func (w *writer) flatten(s strukt) []field {
	var out []field
	for _, f := range s.Fields {
		if f.Inline {
			if embedded, ok := w.structs[f.GoType]; ok {
				out = append(out, w.flatten(embedded)...)
				continue
			}
		}
		out = append(out, f)
	}
	return out
}

func (w *writer) field(indent int, f field) {
	elem := strings.TrimPrefix(f.GoType, "[]")
	switch {
	case strings.HasPrefix(f.GoType, "[]"):
		w.line(indent, "type: array")
		w.describeField(indent, f)
		if v, ok := f.Markers["minItems"]; ok {
			w.line(indent, "minItems: %s", v)
		}
		w.line(indent, "items:")
		if nested, ok := w.structs[elem]; ok {
			w.object(indent+1, nested)
			return
		}
		w.line(indent+1, "type: %s", openAPIType(elem))
	case f.GoType == "yaml.Node" || f.GoType == "map":
		w.line(indent, "type: object")
		w.line(indent, "x-kubernetes-preserve-unknown-fields: true")
		w.describeField(indent, f)
	default:
		if nested, ok := w.structs[elem]; ok {
			w.object(indent, nested)
			if f.Doc != "" {
				w.describe(indent, f.Doc)
			}
			return
		}
		w.line(indent, "type: %s", openAPIType(f.GoType))
		w.describeField(indent, f)
	}
}

// describeField writes the description and the scalar constraints.
func (w *writer) describeField(indent int, f field) {
	if f.Doc != "" {
		w.describe(indent, f.Doc)
	}
	if v, ok := f.Markers["default"]; ok {
		w.line(indent, "default: %s", v)
	}
	if v, ok := f.Markers["enum"]; ok {
		var quoted []string
		for _, item := range strings.Split(v, ";") {
			quoted = append(quoted, strconv.Quote(item))
		}
		w.line(indent, "enum: [%s]", strings.Join(quoted, ", "))
	}
	if v, ok := f.Markers["pattern"]; ok {
		w.line(indent, "pattern: %s", strconv.Quote(v))
	}
	if v, ok := f.Markers["min"]; ok {
		w.line(indent, "minimum: %s", v)
	}
	if v, ok := f.Markers["max"]; ok {
		w.line(indent, "maximum: %s", v)
	}
}

// describe writes a folded block scalar, wrapped so the file stays readable.
func (w *writer) describe(indent int, text string) {
	w.line(indent, "description: >-")
	pad := strings.Repeat("  ", indent+1)
	for _, line := range wrap(text, 76-len(pad)) {
		w.buf.WriteString(pad + line + "\n")
	}
}

func (w *writer) line(indent int, format string, args ...any) {
	w.buf.WriteString(strings.Repeat("  ", indent) + fmt.Sprintf(format, args...) + "\n")
}

func openAPIType(goType string) string {
	switch goType {
	case "string":
		return "string"
	case "int", "int32", "int64":
		return "integer"
	case "bool":
		return "boolean"
	default:
		return "object"
	}
}

func wrap(text string, width int) []string {
	var lines []string
	var line string
	for _, word := range strings.Fields(text) {
		switch {
		case line == "":
			line = word
		case len(line)+1+len(word) <= width:
			line += " " + word
		default:
			lines = append(lines, line)
			line = word
		}
	}
	if line != "" {
		lines = append(lines, line)
	}
	return lines
}

// labelsFooter documents what is not a manifest field. The label names
// themselves live in internal/app/discover.go.
const labelsFooter = `
# ─────────────────────────────────────────────────────────────────────────────
# How a service says it is reached. The label key names the host, the value is
# the port:
#
#   services:
#     app-dev:
#       labels:
#         multiverse.host.app: "4200"              # app-u3.<domain> -> 4200
#         multiverse.host.api: "8001"
#         multiverse.host.api.entrypoint: devapi   # default: web
#         multiverse.host.api.aliases: app,adm     # same service, other names
#         multiverse.host.api.portForward: auto    # also at <ip>:<free port>
#         multiverse.publish: "true"               # keep my published ports
#         multiverse.env.DJANGO_ALLOWED_HOSTS: hosts
#         multiverse.env.DJANGO_CSRF_TRUSTED_ORIGINS: origins
#
# multiverse.env.<VAR> asks for a value only the universe knows, written into
# the generated fragment, which is merged last — so it wins over the service's
# own environment and over any env_file. The sources are:
#
#   origins        every address as an origin, each with its entrypoint's port
#   hosts          every hostname
#   domain         the wildcard domain in use
#   universe       the universe's name
#   slug           the part its hostnames carry
#   host:<key>     one host key's hostname
#   url:<key>      one host key's whole address
#
# A label rather than ${MULTIVERSE_ORIGINS} in the service's environment,
# because a compose file is also run by hand: a reference resolves to the empty
# string when multiversectl is not driving, while a label is inert until it is.
#
# With no labels at all, a service exposing exactly one port is reached at the
# app's own name, so the common case needs nothing. Anything ambiguous — several
# services with ports, or one service with several — is an error naming the
# label to add, rather than a guess.
#
# Variables available to compose files and to an inline overlay:
#
#   UNIVERSE, UNIVERSE_SLUG, UNIVERSE_DIR   its name, the part hostnames carry, its path
#   MULTIVERSE_DOMAIN                       the wildcard domain in use
#   MULTIVERSE_ROOT, MULTIVERSE_PROJECT     the project's root directory, and its name
#   COMPOSE_PROJECT_NAME                    the app's compose project
#   <HOST>_HOST                             one per host key, e.g. APP_HOST
#   <HOST>_URL                              the same with scheme and port
#   MULTIVERSE_HOSTS                        every hostname, comma separated
#   MULTIVERSE_ORIGINS                      every one as an origin, with ports
#   <REPO>_DIR                              one per repository checkout
#   HOST_UID, HOST_GID                      the current user
#
# The last two are what a framework's trusted-origin, allowed-host or CORS
# setting wants: name them in an overlay and the list follows the manifest
# instead of being kept in step by hand.
#
#   overlay:
#     services:
#       web:
#         environment:
#           DJANGO_CSRF_TRUSTED_ORIGINS: "${MULTIVERSE_ORIGINS}"
#           DJANGO_ALLOWED_HOSTS: "${MULTIVERSE_HOSTS}"
# ─────────────────────────────────────────────────────────────────────────────
`
